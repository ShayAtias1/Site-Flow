/** Removes characters XML 1.0 cannot carry, then escapes. */
const xml = (s: string) =>
  s
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F￾￿]/g, '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

/** Text a spreadsheet application could interpret as a formula or command. */
export const looksLikeFormula = (s: string) => /^[=+\-@\t\r＝＋－＠]/.test(s);

const colName = (i: number) => {
  let s = '';
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
};

/** Excel serial date in local time (what the user saw in the app). */
export function excelDate(d: Date) {
  return (d.getTime() - d.getTimezoneOffset() * 60000) / 86400000 + 25569;
}

