function cellXml(ref: string, v: Cell, col: Column): string {
  if (v === null || v === undefined || v === '') return '';
  if (col.type === 'number' && typeof v === 'number' && Number.isFinite(v)) return `<c r="${ref}" s="${S.number}"><v>${v}</v></c>`;
  if ((col.type === 'date' || col.type === 'datetime') && v instanceof Date && !Number.isNaN(v.getTime()))
    return `<c r="${ref}" s="${col.type === 'date' ? S.date : S.datetime}"><v>${excelDate(v)}</v></c>`;
  const s = v instanceof Date ? v.toISOString() : String(v);
  const wrap = col.type === 'longtext';
  const style = looksLikeFormula(s) ? (wrap ? S.wrapQuoted : S.textQuoted) : wrap ? S.wrap : S.text;
  // Excel's limit per cell.
  return `<c r="${ref}" s="${style}" t="inlineStr"><is><t xml:space="preserve">${xml(s.slice(0, 32767))}</t></is></c>`;
}

function sheetXml(spec: SheetSpec) {
  const last = colName(spec.columns.length - 1);
  const header = `<row r="1" ht="30" customHeight="1">${spec.columns
    .map((c, i) => `<c r="${colName(i)}1" s="${S.header}" t="inlineStr"><is><t xml:space="preserve">${xml(c.header)}</t></is></c>`)
    .join('')}</row>`;
  const body = spec.rows
    .map((r, ri) => `<row r="${ri + 2}">${spec.columns.map((c, ci) => cellXml(`${colName(ci)}${ri + 2}`, r[ci], c)).join('')}</row>`)
    .join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheetPr><pageSetUpPr fitToPage="1"/></sheetPr>
<dimension ref="A1:${last}${spec.rows.length + 1}"/>
<sheetViews><sheetView rightToLeft="1" workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/><selection pane="bottomLeft" activeCell="A2" sqref="A2"/></sheetView></sheetViews>
<sheetFormatPr defaultRowHeight="15"/>
<cols>${spec.columns.map((c, i) => `<col min="${i + 1}" max="${i + 1}" width="${c.width}" customWidth="1"/>`).join('')}</cols>
<sheetData>${header}${body}</sheetData>
<autoFilter ref="A1:${last}${spec.rows.length + 1}"/>
<pageMargins left="0.4" right="0.4" top="0.5" bottom="0.5" header="0.3" footer="0.3"/>
<pageSetup paperSize="9" orientation="landscape" fitToWidth="1" fitToHeight="0"/>
</worksheet>`;
}

/** Sheet names: at most 31 characters, none of []:*?/\ */
const sheetName = (s: string) => s.replace(/[[\]:*?/\\]/g, ' ').slice(0, 31) || 'Sheet1';

